"""Write AuraLab's list of the abilities to learn the auras of: every entry of
Modules/PartyCD/Spells.lua, by the spell IDs it is cast as.

    python tools/auralab_targets.py              # writes ../AuraLab/Targets.lua

AuraLab (a separate development addon, ../AuraLab) learns, while auras are not
secret, which auras a cast of one of these leaves on the caster, on a teammate
and on the caster's target, for the player's casts and the party's. What it
learned is compared with Spells.lua by tools/auralab_check.py.
"""
import os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from candidates import listed   # noqa: E402
from talentdata import ROOT     # noqa: E402

OUT = os.path.join(os.path.dirname(ROOT), "AuraLab", "Targets.lua")

def main():
    entries = listed()
    lines = ["-- Generated by CombatKit's tools/auralab_targets.py from Modules/PartyCD/Spells.lua.",
             "-- Do not edit: run the script again when the list changes.",
             "-- The spells whose auras the lab learns: cast spell ID -> the ability's key (its",
             "-- own ID in Spells.lua; a version cast as another spell maps to it).",
             "AuraLabTargets = {"]
    seen = set()
    for token, sid, seen_as, casts, auras, comment in entries:
        for cast in [sid] + casts:
            if cast in seen:
                continue
            seen.add(cast)
            note = comment if cast == sid else "cast of %d: %s" % (sid, comment)
            lines.append("\t[%d] = %d,  -- %s %s" % (cast, sid, token, note[:80]))
    lines.append("}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s: %d casts of %d abilities" % (OUT, len(seen), len(entries)))

if __name__ == "__main__":
    main()
